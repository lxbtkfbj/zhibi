async function json(request: APIRequestContext, path: string, method = 'GET', data?: unknown) {
  const response = await request.fetch(`/api${path}`, { method, data })
  expect(response.ok(), `${method} ${path}: ${await response.text()}`).toBeTruthy()
  return response.status() === 204 ? undefined : response.json()
}
async function waitJob(request: APIRequestContext, id: string, kind?: string) {
  let result: any
  await expect.poll(async () => {
    result = await json(request, `/jobs/${id}`)
    if (result.status === 'failed') throw new Error(result.error)
    return kind ? result.pending?.kind : result.status
  }, { timeout: 120_000, intervals: [500, 1000, 2000] }).toBe(kind || 'succeeded')
  return result
}
async function settings(page: Page, tab: string) {
  await page.getByRole('button', { name: '设置', exact: true }).click()
  await page.getByRole('tab', { name: tab, exact: true }).click()
}
