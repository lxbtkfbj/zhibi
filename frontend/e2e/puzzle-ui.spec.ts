import { test, expect, type APIRequestContext, type Page } from '@playwright/test'
import fs from 'node:fs/promises'
import path from 'node:path'
import type { BookDetail, Job, StoryNode } from '../src/api/types'

const evidence = path.resolve('../docs/第一包验收')
async function json<T>(request: APIRequestContext, route: string): Promise<T> {
  const response = await request.get(`/api${route}`)
  expect(response.ok(), `${route}: ${await response.text()}`).toBeTruthy()
  return response.json()
}
async function settled(request: APIRequestContext, id: string, kind?: string, piece?: string): Promise<Job> {
  let job: Job
  await expect.poll(async () => {
    job = await json<Job>(request, `/jobs/${id}`)
    if (job.status === 'failed') throw new Error(job.error)
    return ['waiting_author', 'succeeded'].includes(job.status) && (!kind || job.pending?.kind === kind) && (!piece || (job.pending?.kind === 'setup_piece' && job.pending.piece === piece))
  }, { timeout: 240_000, intervals: [250, 500, 1000] }).toBe(true)
  return job!
}
async function shot(page: Page, name: string) {
  await fs.mkdir(evidence, { recursive: true })
  // 等待本页约 0.28 秒的进场动效，避免把半透明过渡当作最终界面。
  await page.waitForTimeout(500)
  await page.screenshot({ path: path.join(evidence, `任务3-${name}.png`) })
}
async function act(page: Page, action: () => Promise<unknown>, endpoint = '/piece') {
  const pending = page.waitForResponse(r => r.url().endsWith(endpoint) && r.request().method() === 'POST')
  await action()
  const response = await pending
  expect(response.ok(), await response.text()).toBeTruthy()
  return await response.json() as Job
}
async function confirm(page: Page, request: APIRequestContext, id: string, next?: string) {
  await act(page, () => page.getByRole('button', { name: '确认这一块', exact: true }).click())
  return settled(request, id, next ? 'setup_piece' : undefined, next)
}
async function follow(page: Page) {
  if (await page.getByTestId('resume-follow').count()) await page.getByTestId('resume-follow').click()
}
async function create(page: Page, request: APIRequestContext, idea: string, mode = 'puzzle') {
  await page.goto('/')
  await page.getByRole('button', { name: mode === 'puzzle' ? '逐块确认（推荐）' : '一口气出方案', exact: true }).click()
  if (mode === 'oneshot') {
    const ask = page.getByRole('button', { name: '先问我几个问题' })
    if (await ask.getAttribute('aria-pressed') === 'true') await ask.click()
  }
  await page.locator('textarea').first().fill(idea)
  const response = page.waitForResponse(r => r.url().endsWith('/api/books') && r.request().method() === 'POST')
  await page.getByRole('button', { name: '交给编辑部', exact: true }).click()
  const result = await (await response).json() as { book: BookDetail; job: Job }
  await settled(request, result.job.id, mode === 'puzzle' ? 'setup_directions' : 'setup_review')
  return result
}
async function choose(page: Page, request: APIRequestContext, id: string) {
  await act(page, () => page.getByRole('button', { name: '选这个', exact: true }).first().click(), '/directions')
  await settled(request, id, 'setup_piece', 'concept')
  await expect(page.getByTestId('decision-bar')).toContainText('待你确认：定调')
}

