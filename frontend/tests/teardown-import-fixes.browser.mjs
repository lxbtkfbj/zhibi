/** 小修真实 API / 真鼠标验收；合成种子只写进隔离副本，不调用模型。 */
import assert from 'node:assert/strict'
import fs from 'node:fs'
import path from 'node:path'
import { chromium, expect } from '@playwright/test'
import { cleanTitle } from '../src/lib/status.ts'

const BASE = process.env.ZHIBI_FIXES_URL
const API = process.env.ZHIBI_FIXES_API
assert.ok(BASE && API && process.env.ZHIBI_FIXES_FIXTURE, '指定隔离前后端及合成种子清单')
for (const address of [BASE, API]) {
  const url = new URL(address)
  assert.ok(['127.0.0.1', 'localhost'].includes(url.hostname) && url.port && !['8000', '4320'].includes(url.port))
}
const fixture = JSON.parse(fs.readFileSync(process.env.ZHIBI_FIXES_FIXTURE, 'utf8'))
const OUT = path.resolve(import.meta.dirname, '../../docs/拆书导入验收')
const browser = await chromium.launch({ executablePath: process.env.ZHIBI_CHROMIUM ?? 'C:/Program Files/Google/Chrome/Application/chrome.exe' })
const context = await browser.newContext({ viewport: { width: 1600, height: 1000 } })
const errors = [], results = [], external = []
const page = await context.newPage()
page.on('pageerror', error => errors.push(String(error)))
await context.route('**/*', route => {
  const url = new URL(route.request().url())
  if (url.protocol.startsWith('http') && !['127.0.0.1', 'localhost'].includes(url.hostname)) { external.push(url.origin); return route.abort() }
  return route.continue()
})
await page.addInitScript(() => {
  if (!localStorage.getItem('zhibi:editorial-dock')) localStorage.setItem('zhibi:editorial-dock', 'float')
  localStorage.setItem('zhibi:appearance', JSON.stringify({ theme: 'paper', deskScale: 100 }))
})
const check = async (name, run) => { await run(); results.push({ name, passed: true }); console.log('PASS', name) }
const tab = name => page.locator('header.top nav').getByText(name, { exact: true })
const row = name => page.locator('.toc .row').filter({ hasText: name })
const shot = name => page.screenshot({ path: path.join(OUT, `小修-${name}.png`) })
const get = async suffix => { const response = await fetch(API + suffix); assert.ok(response.ok); return response.json() }
let pending
try {
  await check('3 有卷合成文件确认页没有分卷块，统计是新写法', async () => {
    const form = new FormData()
    form.set('file', new Blob(['第一卷 开始\n第一章 初见\n合成正文。\n第二卷 继续\n第二章 后续\n新的正文。']), '小修待确认.txt')
    const response = await fetch(API + '/teardown', { method: 'POST', body: form })
    assert.equal(response.status, 201)
    pending = await response.json()
    assert.ok(!('volume_mode' in pending) && !('largest_volume' in pending))
    await page.goto(`${BASE}/teardown/${pending.book_id}`)
    await expect(page.getByLabel('书名', { exact: true })).toBeVisible()
    await expect(page.getByRole('heading', { name: '分卷', exact: true })).toHaveCount(0)
    await expect(page.getByText('共 10 字 · 2 章，拆的时候主编按剧情分卷', { exact: true })).toBeVisible()
    await shot('3-确认页')
  })
  await page.goto(`${BASE}/desk/${fixture.teardown.book}`)
  await check('4 真鼠标选择浮窗旧对话，空白标题栏仍能拖动', async () => {
    const floating = page.getByTestId('editorial-floating')
    await expect(floating).toBeVisible()
    await floating.getByRole('button', { name: '以前的对话', exact: true }).click()
    await floating.getByRole('option').filter({ hasText: '合成旧对话' }).click()
    await expect(floating.getByRole('listbox')).toHaveCount(0)
    await expect(floating.getByText('以前的对话「合成旧对话」', { exact: false })).toBeVisible()
    await expect(floating.getByText('旧消息：小修鼠标验收', { exact: true })).toBeVisible()
    const before = await floating.boundingBox(), title = await floating.getByTestId('editorial-header').boundingBox()
    // 标题与工具之间的空白，用 mouse.down/move/up，不发送脚本点击。
    await page.mouse.move(title.x + 210, title.y + title.height / 2)
    await page.mouse.down()
    await page.mouse.move(title.x + 130, title.y + title.height / 2 - 45, { steps: 12 })
    await page.mouse.up()
    const after = await floating.boundingBox()
    assert.ok(Math.abs(after.x - before.x) > 40 && Math.abs(after.y - before.y) > 20)
    await shot('4-浮窗旧对话')
    await floating.getByTestId('editorial-header').getByRole('button', { name: '收起', exact: true }).click()
  })
  await check('5 搜索隐藏无结果类别、匹配计数自动展开，收起和清空恢复', async () => {
    await tab('设定').click()
    const search = page.getByRole('textbox', { name: '找人物、地方、规矩……', exact: true })
    const categoryState = () => page.locator('.toc .row.unit').evaluateAll(rows => rows.map(row => ({ name: row.textContent, closed: row.classList.contains('closed') })))
    const before = await categoryState()
    await search.fill('陈')
    await expect(row('金手指')).toHaveCount(0)
    await expect(row('等级体系')).not.toHaveClass(/closed/)
    await expect(row('等级体系').locator('.n')).toHaveText('1 套')
    await expect(row('角色列表').locator('.n')).toHaveText('1')
    await expect(row('地点列表').locator('.n')).toHaveText('1')
    await expect(row('设定总览')).toBeVisible()
    await expect(row('世界概况')).toBeVisible()
    await row('等级体系').locator('svg').click()
    await expect(row('等级体系')).toHaveClass(/closed/)
    await expect(page.locator('.toc').getByText('陈家境界', { exact: true })).toHaveCount(0)
    // 选中命中条目也不能把搜索的自动展开写进常态目录。
    await page.locator('.toc').getByText('陈枭', { exact: true }).click()
    await expect(page.locator('.page ul.moments > li')).toHaveCount(3)
    await shot('5-设定搜索')
    await search.fill('')
    assert.deepEqual(await categoryState(), before)
  })
  await check('6 一句话卡逐章记录合并排序、章号可点，全卡不增加该栏', async () => {
    const section = page.locator('.page .sec').filter({ has: page.getByText('出场那几章', { exact: false }) })
    await expect(section.locator('.label .n')).toHaveText('逐章记录里写的')
    await expect(section.locator('ul.moments > li')).toHaveCount(3)
    await expect(section.locator('.ch')).toHaveText(['第 1 章', '第 2 章', '第 3 章'])
    await expect(section.locator('li').first()).toContainText('陈枭第1章出场；以别名出现')
    await expect(section.locator('.shows').first()).toHaveText('变化：改变1；准备离开')
    await shot('6-出场那几章')
    await section.locator('.ch').first().click()
    await expect(tab('大纲')).toHaveClass(/on/)
    await expect(page.locator('.page h1')).toContainText('合成章1')
    await tab('设定').click()
    await row('角色列表').locator('svg').click()
    await page.locator('.toc').getByText('苏明', { exact: true }).click()
    await expect(page.locator('.page h1')).toHaveText('苏明')
    await expect(page.locator('.page .label').filter({ hasText: '出场那几章' })).toHaveCount(0)
  })
  await check('7 篇默认展开、整组缩进14px，选择/箭头折叠、刷新和跨页章号展开', async () => {
    await tab('大纲').click()
    const first = row('合成第1篇'), second = row('合成第2篇')
    await expect(page.locator('.arc-volumes')).toHaveCount(2)
    assert.deepEqual(await page.locator('.arc-volumes').evaluateAll(groups => groups.map(group => getComputedStyle(group).marginLeft)), ['14px', '14px'])
    const arcBox = await first.boundingBox(), volumeBox = await row('合成卷1').boundingBox()
    assert.equal(volumeBox.x - arcBox.x, 14)
    await second.click()
    await expect(page.locator('.arc-volumes')).toHaveCount(2)
    await second.click()
    await expect(second).toHaveAttribute('aria-expanded', 'false')
    await expect(row('合成卷2')).toHaveCount(0)
    await shot('7-篇缩进和收起')
    await page.reload()
    await expect(second).toHaveAttribute('aria-expanded', 'false')
    await second.click()
    await expect(row('合成卷2')).toBeVisible()
    await second.locator('svg').click()
    await expect(second).toHaveAttribute('aria-expanded', 'false')
    await tab('设定').click()
    await page.getByRole('textbox', { name: '找人物、地方、规矩……', exact: true }).fill('陈')
    await page.locator('.toc').getByText('陈枭', { exact: true }).click()
    await page.locator('.page .moments .ch').getByText('第 3 章', { exact: true }).click()
    await expect(second).toHaveAttribute('aria-expanded', 'true')
    await expect(row('合成章3')).toBeVisible()
  })
  await check('8 换书框样式/顺序/当前项/关闭，写书及拆书入口与书房一致', async () => {
    const trigger = page.getByRole('button', { name: '换一本书', exact: true })
    await trigger.click()
    const menu = page.getByRole('listbox', { name: '换一本书', exact: true })
    await expect(menu).toBeVisible()
    const bounds = await menu.boundingBox(), cover = await page.locator('.mini-cover').boundingBox()
    assert.equal(bounds.x, cover.x)
    assert.equal(bounds.width, 320)
    assert.ok(bounds.height <= 360)
    const books = await get('/books')
    const expected = [...books.filter(book => book.source !== 'teardown'), ...books.filter(book => book.source === 'teardown')].map(book => cleanTitle(book.title))
    assert.deepEqual(await menu.locator('.book-switch-row > span').allTextContents(), expected)
    await expect(menu.locator('.book-switch-row.current small')).toHaveText('正在看')
    await shot('8-换一本书')
    const before = page.url()
    await menu.locator('.current').click()
    await expect(menu).toHaveCount(0)
    assert.equal(page.url(), before)
    await trigger.click(); await page.keyboard.press('Escape'); await expect(menu).toHaveCount(0)
    await trigger.click(); await tab('设定').click(); await expect(menu).toHaveCount(0)
    await page.getByRole('textbox', { name: '找人物、地方、规矩……', exact: true }).fill('陈')
    await trigger.click()
    await menu.locator(`a[href="/desk/${fixture.new.book}"]`).click()
    await page.waitForURL(`${BASE}/desk/${fixture.new.book}`)
    await expect(tab('设定')).toHaveClass(/on/)
    await expect(page.getByRole('textbox', { name: '找人物、地方、规矩……', exact: true })).toHaveValue('')
    await expect(page.getByText('以前的对话「合成旧对话」', { exact: false })).toHaveCount(0)
    // 写的书同样支持篇折叠。
    await tab('大纲').click()
    await expect(page.locator('.arc-volumes')).toHaveCount(2)
    await row('合成第1篇').locator('svg').click()
    await expect(row('合成第1篇')).toHaveAttribute('aria-expanded', 'false')
    await page.getByRole('button', { name: '换一本书', exact: true }).click()
    await page.getByRole('listbox', { name: '换一本书', exact: true }).locator(`a[href="/desk/${fixture.teardown.book}"]`).click()
    await page.waitForURL(`${BASE}/desk/${fixture.teardown.book}`)
    await expect(tab('简介')).toHaveClass(/on/)
    await page.getByRole('button', { name: '换一本书', exact: true }).click()
    await page.getByRole('listbox', { name: '换一本书', exact: true }).locator(`a[href="/teardown/${pending.book_id}"]`).click()
    await page.waitForURL(`${BASE}/teardown/${pending.book_id}`)
    await expect(page.getByLabel('书名', { exact: true })).toBeVisible()
  })
  assert.deepEqual(errors, [])
  assert.deepEqual(external, [])
  fs.writeFileSync(path.join(OUT, '小修-界面交互.json'), JSON.stringify({ base: BASE, api: API, fixtures: fixture, confirming_book: pending.book_id, results, errors, externalRequests: external, realMouse: true, realModelCalls: 0 }, null, 2) + '\n')
} catch (error) {
  fs.writeFileSync(path.resolve(import.meta.dirname, '../../data/import-fixes-20261021/browser-failure.txt'), await page.locator('body').innerText())
  await page.screenshot({ path: path.resolve(import.meta.dirname, '../../data/import-fixes-20261021/browser-failure.png') })
  throw error
} finally { await browser.close() }
