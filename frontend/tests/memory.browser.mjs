async function shot(name) { await page.evaluate(async () => { await document.fonts.ready; await Promise.allSettled(document.getAnimations().filter(animation => Number.isFinite(animation.effect?.getComputedTiming().endTime)).map(animation => animation.finished)) }); await page.screenshot({ path: path.join(SHOTS, name) }); report.screenshots.push(name) }
async function send(id, text) {
  await type(composer(), text)
  const response = page.waitForResponse(r => r.request().method() === 'POST' && new URL(r.url()).pathname === `/api/books/${id}/notes`)
  await composer().press('Enter')
  const r = await response; assert.equal(r.status(), 201)
  const note = await r.json()
  await expect.poll(async () => (await get(`/books/${id}/meeting?limit=2000`)).find(row => row.id === note.id)?.payload?.outcome?.kind, { timeout: 90000 }).not.toBe('pending')
  return (await get(`/books/${id}/meeting?limit=2000`)).find(row => row.id === note.id)
}
