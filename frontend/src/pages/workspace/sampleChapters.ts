const C1 = `青冥宗外门杂役院的早饭，是一勺稀粥，半个杂面馒头。
陈默端着碗蹲在灶房门口，馒头还没咬下去，眼睛先疼了一下。
像有人往眼眶里撒了一把沙。他使劲眨了两下，再睁开时，整个院子都变了。
排队打粥的杂役，头顶上全都悬着一行淡淡的字。
打头的王胖子，头顶写着“四十一年零三个月”。他身后的瘦猴，“二十六年”。再往后，一个个数字浮在半空，像赶集时挂在摊子上的价签。
陈默手一抖，粥洒了半碗。
他没出声。在杂役院活了五年，他学会的头一件事，就是遇事先别出声。
他低头喝粥，眼角一个一个去扫。
灶台后头的孙婆婆，头顶是一团糊住的墨，什么也看不清。陈默多看了两眼，眼睛又是一阵刺疼，鼻子底下一热，抹了一把，指头上全是血。
他赶紧挪开目光。
就在这时，院门口有人笑了一声。
“都吃着呢？吃饱了好干活。”
来的是传功执事赵长河。圆脸，眯眼，袖口永远干干净净，见谁都先笑。外门三千弟子，没人见他发过火。
陈默抬头看了一眼。
只一眼，后背的汗毛全竖起来了。
赵长河头顶的字，是整个院子里最短的一行——
“三天”。
筑基后期的修士，寿元少说两百年。这位执事上个月刚过一百一十岁的寿辰，宗门里都说他还有一百年好活。
可他头顶写着三天。
陈默把碗端到嘴边，借着碗沿挡住脸，一口一口地喝。粥早就凉了，他喝得很慢。
“今年的筑基丹，炼好了。”赵长河拍了拍手，身后两个弟子抬上来一只红漆木箱，“老祖开恩，这一批多出三枚，赏给杂役院。”
院子里一下炸开了锅。
筑基丹。外门弟子熬十年都未必轮得上一枚，杂役更是想都不敢想。吃下去当场破境，从此就是正经的修士，再也不用劈柴挑水。
王胖子的眼睛都红了。
陈默却在看那些围上去的人头顶。数字没变。可他总觉得哪里不对——一个只剩三天的人，为什么笑得这么高兴？
“陈默。”
他手里的碗一顿。
赵长河正越过人群看着他，笑得眼睛都没了：“过来，领丹。”`

const C2 = `陈默是被抬回去的。
他走到红漆箱子前，两腿一软，直挺挺地栽在了赵长河脚边，嘴里吐着白沫，浑身抽成一团。
“羊角风！”有人喊了一声，人群呼啦一下散开。
赵长河蹲下来，拍了拍他的脸，叹了口气：“可惜了。先抬回去，丹给他留着。”
被人扛回柴房的一路上，陈默始终闭着眼，牙关咬得死紧。白沫是早上那口粥，抽搐是他在心里数着节拍抽的。杂役院里装病的法子，他五年来见过不下二十种，这是最难被拆穿的一种。
柴房门一关，他就睁开了眼。
丹给他留着。
这五个字比赵长河头顶的“三天”还让他发冷。
天黑以后，陈默摸去了外门弟子住的东院。他要看一样东西。
去年发过一批筑基丹，吃过的七个师兄如今都住在东院，已经是正经的修士了。陈默趴在墙头，借着廊下的灯笼，一个一个看过去。
第一个，“两天十一个时辰”。
第二个，“两天十一个时辰”。
第三个、第四个……一直到第七个。
七个人，七个不同的年纪，七种不同的修为。头顶的数字却一模一样，连时辰都对得上，像是同一支笔、同一口气写下的。
陈默趴在墙头上，夜风吹得他浑身发冷。
他想起赵长河头顶的三天，又低头算了算。今天过去了一个白天。
这七个师兄的死期，和传功执事的死期，是同一天。
同一个时辰。
而那一天，就是三天后。`

const C3 = `第二天一早，赵长河亲自来了柴房。
他没带人，手里托着一只巴掌大的玉盒，进门先把门掩上，笑眯眯地在床沿坐下。
“好些了？”
陈默缩在被子里，声音发虚：“回执事，好、好多了。”
“那就好。”赵长河打开玉盒，一枚龙眼大小的丹药躺在里面，泛着温润的青光，“趁热吃。凉了药性就散了。”
陈默盯着那枚丹。他看不见丹的寿命，可他看得见赵长河——头顶的数字，“两天零四个时辰”。
比昨天又少了。少得比时辰走得快。
“执事，”陈默往后缩了缩，“小的……小的手不方便。”
他把右手从被子里伸出来。
那只手少了半截小指，断口早就长平了，是十二岁那年被卖进宗门时，人牙子为了让他“老实点”剁的。五年来他从没跟人提过，平时干活都把那根手指蜷在掌心里。
赵长河的笑容顿了一下。
“断指之人，筋脉不全，”陈默低着头，把早就想好的话一句句往外送，“小的听讲经的师兄说过，吃筑基丹要灵气走遍十二经，断了的地方，会把丹力憋在里头，炸了经脉……小的命贱，死了不要紧，就怕糟蹋了老祖赏的丹。”
屋里静了好一会儿。
赵长河伸手捏住他那只断手，翻过来，翻过去，指腹在断口上来回摩挲。他的手很热，热得不像一个快死的人。
“倒是个懂事的。”他终于松开，把玉盒合上，揣回袖子里，“这事我回头问问丹房。你好好歇着。”
他起身往外走。
陈默一直低着头，直到脚步声到了门口，才敢抬眼。
赵长河正好在门口停住，回过头，看了他一眼。那一眼里没有笑。
陈默的目光不受控制地往上抬了一寸。
执事头顶的数字，变了。
“两天零四个时辰”，正在一点一点地往上涨。`

const C4 = `陈默一夜没睡。
他把这两天看见的数字，一个一个在心里排开：赵长河的寿命，昨天三天，今早两天零四个时辰，走出柴房时又往上涨了一截。东院七个师兄，两天十一个时辰，和执事同一天死。
一个人的寿命，不该涨，也不该这么一截一截地掉。除非——
除非它不是自己在走。
天刚蒙蒙亮，陈默就挑着水桶去了传功堂。杂役给执事院子送水，再正常不过。
他把水倒进缸里，蹲在廊下慢慢擦桶，眼睛一直落在正堂里打坐的赵长河身上。
这一次，他没有挪开目光。
一息，两息……眼眶开始发烫，鼻血又流了下来，他拿袖子堵住，硬生生地盯着。他知道规矩：过了十息，折的就是自己的寿。
到第九息的时候，他看见了。
赵长河头顶那行字的边上，有一缕极细的白线。细得像蛛丝，从数字的末尾抽出来，往门外飘，穿过院墙，穿过晨雾，一直往后山的方向去。
每隔几息，白线轻轻一抖，执事的数字就少一点。
不是在减。是有人在收。
陈默眼前一黑，差点从廊下栽下去。他死死抓着水桶，把那口血咽回喉咙里，挑起空桶就往外走，一步都没敢停。
出了传功堂，他才回头看了一眼后山。
晨雾散开了一角。
青冥宗后山的最高处，是老祖闭关了三百年的洞府。
那缕白线的另一头，就攥在那里。`

